<?php
// Rank Math-style XML sitemaps (used when SEO → mode is "Advanced"):
//   /sitemap_index.xml → post-sitemap.xml (+ post-sitemap2.xml … 1,000 per file), page-sitemap.xml, category-sitemap.xml,
//   post_tag-sitemap.xml, author-sitemap.xml, state-sitemap.xml and news-sitemap.xml — styled in the browser by /main-sitemap.xsl.
// Each address is a tiny "name.xml.php" file next to index.php, served by the site's existing ".php-less address" rule.
require_once dirname(__DIR__) . '/includes/config.php';
require_once INCLUDES_PATH . '/functions.php';
require_once INCLUDES_PATH . '/seo.php';

function edu_sm_headers(): void
{
    // No visitor session or "no-store" for search engines: a cacheable, cookie-free XML response.
    if (session_status() === PHP_SESSION_ACTIVE) session_abort();
    header_remove('Set-Cookie');
    header_remove('Pragma');
    header_remove('Expires');
    header('Content-Type: application/xml; charset=UTF-8');
    header('Cache-Control: public, max-age=900');
    header('X-Robots-Tag: noindex, follow');
}

function edu_sm_base(): string
{
    return rtrim(SITE_URL, '/');
}

function edu_sm_date(?string $d): string
{
    return $d ? gmdate('Y-m-d\TH:i:s+00:00', strtotime($d)) : '';
}

function edu_sm_x(string $s): string
{
    return htmlspecialchars($s, ENT_XML1 | ENT_QUOTES, 'UTF-8');
}

/** post-sitemapN.xml is served by a tiny post-sitemapN.xml.php (the web server can't take new rewrite rules), made
 *  only when that many posts exist — so the site folder holds just the files that are needed. */
function edu_sm_post_stub(int $n): void
{
    $f = ROOT_PATH . "/post-sitemap$n.xml.php";
    if ($n > 1 && $n <= 50 && !is_file($f)) {
        @file_put_contents($f, "<?php\n// post-sitemap$n.xml — see includes/sitemaps.php (made when needed)\nrequire __DIR__ . \"/includes/sitemaps.php\";\nedu_sm_serve(\$pdo, 'post', $n);\n");
    }
}

/** Lists of sitemaps that exist right now, with their newest change. */
function edu_sm_list(PDO $pdo): array
{
    $b = edu_sm_base();
    $out = [];
    $per = max(1, min(50000, (int)seo_opt('sm_per') ?: 200));
    if (seo_opt('sm_posts') === '1') {
        $r = $pdo->query("SELECT COUNT(*) n, MAX(COALESCE(updated_at, date)) m FROM posts WHERE status = 'published'" . edu_sm_exclude_sql())->fetch(PDO::FETCH_ASSOC);
        $pages = max(1, (int)ceil($r['n'] / $per));
        for ($i = 1; $i <= min($pages, 50); $i++) { if ($i > 1) edu_sm_post_stub($i); $out[] = [$b . '/post-sitemap' . ($i > 1 ? $i : '') . '.xml', $r['m']]; }
    }
    $latest = $pdo->query("SELECT MAX(COALESCE(updated_at, date)) FROM posts WHERE status = 'published'")->fetchColumn();
    if (seo_opt('sm_pages') === '1') $out[] = [$b . '/page-sitemap.xml', $latest];
    if (seo_opt('sm_categories') === '1') $out[] = [$b . '/category-sitemap.xml', $latest];
    if (seo_opt('sm_tags') === '1' && seo_opt('noindex_tags') !== '1' && (int)$pdo->query("SELECT COUNT(*) FROM post_tag")->fetchColumn()) $out[] = [$b . '/post_tag-sitemap.xml', $latest];
    if (seo_opt('sm_authors') === '1' && seo_opt('noindex_authors') !== '1') $out[] = [$b . '/author-sitemap.xml', $latest];
    if (seo_opt('sm_states') === '1' && (int)$pdo->query("SELECT COUNT(*) FROM posts WHERE state_id IS NOT NULL AND status = 'published'")->fetchColumn()) $out[] = [$b . '/state-sitemap.xml', $pdo->query("SELECT MAX(COALESCE(updated_at, date)) FROM posts WHERE state_id IS NOT NULL AND status = 'published'")->fetchColumn()];
    if (edu_seo_module('news_sitemap')) $out[] = [$b . '/news-sitemap.xml', $pdo->query("SELECT MAX(date) FROM posts WHERE status = 'published'")->fetchColumn()];
    return $out;
}

function edu_sm_index(PDO $pdo): void
{
    edu_sm_headers();
    echo '<?xml version="1.0" encoding="UTF-8"?>' . "\n" . '<?xml-stylesheet type="text/xsl" href="' . preg_replace('#^https?:#', '', edu_sm_base()) . '/main-sitemap.xsl"?>' . "\n";
    echo '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
    foreach (edu_sm_list($pdo) as [$loc, $mod]) {
        echo "\t<sitemap>\n\t\t<loc>" . edu_sm_x($loc) . "</loc>\n" . ($mod ? "\t\t<lastmod>" . edu_sm_date($mod) . "</lastmod>\n" : '') . "\t</sitemap>\n";
    }
    echo "</sitemapindex>\n<!-- XML Sitemap generated by " . edu_sm_x(edu_site_name()) . " SEO -->";
}

/** One urlset. $rows: [loc, lastmod, images[]] */
function edu_sm_urlset(array $rows): void
{
    edu_sm_headers();
    echo '<?xml version="1.0" encoding="UTF-8"?>' . "\n" . '<?xml-stylesheet type="text/xsl" href="' . preg_replace('#^https?:#', '', edu_sm_base()) . '/main-sitemap.xsl"?>' . "\n";
    echo '<urlset xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd http://www.google.com/schemas/sitemap-image/1.1 http://www.google.com/schemas/sitemap-image/1.1/sitemap-image.xsd" xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n";
    foreach ($rows as $r) {
        echo "\t<url>\n\t\t<loc>" . edu_sm_x($r[0]) . "</loc>\n";
        if (!empty($r[1])) echo "\t\t<lastmod>" . edu_sm_date($r[1]) . "</lastmod>\n";
        foreach ($r[2] ?? [] as $img) echo "\t\t<image:image>\n\t\t\t<image:loc>" . edu_sm_x($img) . "</image:loc>\n\t\t</image:image>\n";
        echo "\t</url>\n";
    }
    echo "</urlset>\n<!-- XML Sitemap generated by " . edu_sm_x(edu_site_name()) . " SEO -->";
}

function edu_sm_not_found(): void
{
    http_response_code(404);
    edu_sm_headers();
    echo '<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"></urlset>';
}

/** Serves one sitemap by type ('index', 'post', 'page', 'category', 'post_tag', 'author', 'state'); $n = file number for posts. */
function edu_sm_serve(PDO $pdo, string $type, int $n = 1): void
{
    if (!edu_seo_module('sitemap') || seo_opt('noindex_site') === '1') {
        // Original SEO mode: the original /sitemap.xml is the sitemap.
        header('Location: ' . edu_sm_base() . '/sitemap.xml', true, 302);
        exit;
    }
    $b = edu_sm_base();
    if ($type === 'index') { edu_sm_index($pdo); return; }
    $rows = [];
    if ($type === 'post' && seo_opt('sm_posts') === '1') {
        $per = max(1, min(50000, (int)seo_opt('sm_per') ?: 200));
        $st = $pdo->query("SELECT p.id, p.slug, p.date, p.updated_at, p.content, m.file_path FROM posts p LEFT JOIN media m ON m.id = p.featured_image_id
            WHERE p.status = 'published'" . edu_sm_exclude_sql('p.') . " AND NOT EXISTS (SELECT 1 FROM post_meta pm WHERE pm.post_id = p.id AND pm.meta_key = 'noindex' AND pm.meta_value = '1')
            ORDER BY p.date DESC LIMIT $per OFFSET " . (($n - 1) * $per));
        $all = $st->fetchAll(PDO::FETCH_ASSOC);
        if (!$all && $n > 1) { edu_sm_not_found(); return; }
        foreach ($all as $p) {
            $imgs = [];
            if (seo_opt('sm_images') === '1') {
                if ($p['file_path'] && seo_opt('sm_featured') === '1') $imgs[] = $b . '/' . ltrim($p['file_path'], '/');
                if (preg_match_all('#<img[^>]+src=["\']([^"\']+)#i', (string)$p['content'], $m)) {
                    foreach (array_slice($m[1], 0, 10) as $src) {
                        if (str_starts_with($src, 'data:')) continue;
                        $imgs[] = preg_match('#^https?://#', $src) ? $src : $b . '/' . ltrim($src, '/');
                    }
                }
            }
            $rows[] = [$b . postUrl($p['slug'], (int)$p['id']), $p['updated_at'] ?: $p['date'], array_values(array_unique($imgs))];
        }
    } elseif ($type === 'page' && seo_opt('sm_pages') === '1') {
        $last = $pdo->query("SELECT MAX(COALESCE(updated_at, date)) FROM posts WHERE status = 'published'")->fetchColumn();
        $rows[] = [$b . '/', $last];
        foreach (['latest-updates', 'categories', 'state-jobs'] as $p) $rows[] = [$b . '/' . $p, $last];
        // Latest Jobs only once a post has a job card (the empty page is noindex)
        $jobsLast = $pdo->query("SELECT MAX(COALESCE(p.updated_at, p.date)) FROM posts p JOIN post_meta jm ON jm.post_id = p.id AND jm.meta_key = 'job_card' AND jm.meta_value = '1' WHERE p.status = 'published'")->fetchColumn();
        if ($jobsLast) $rows[] = [$b . '/latest-jobs', $jobsLast];
        try {
            $sp = $pdo->query("SELECT slug, updated_at FROM site_pages WHERE status = 'published' AND (noindex IS NULL OR noindex = 0) ORDER BY title")->fetchAll(PDO::FETCH_ASSOC);
        } catch (Throwable $e) { $sp = []; }
        $have = array_column($sp, 'slug');
        foreach ($sp as $p) $rows[] = [$b . '/' . $p['slug'], $p['updated_at']];
        foreach (['about-us', 'contact-us', 'privacy-policy', 'terms-of-service', 'cookie-policy', 'editorial-policy', 'disclaimer'] as $p) {
            if (!in_array($p, $have, true) && is_file(ROOT_PATH . "/pages/$p.php")) $rows[] = [$b . '/' . $p, date('Y-m-d H:i:s', filemtime(ROOT_PATH . "/pages/$p.php"))];
        }
    } elseif ($type === 'category' && seo_opt('sm_categories') === '1') {
        foreach ($pdo->query("SELECT c.slug, MAX(COALESCE(p.updated_at, p.date)) m FROM categories c JOIN posts p ON p.category_id = c.id AND p.status = 'published' WHERE 1" . edu_sm_exclude_terms('c.id') . " GROUP BY c.id ORDER BY c.name") as $c) $rows[] = [$b . '/categories/' . $c['slug'], $c['m']];
    } elseif ($type === 'post_tag' && seo_opt('sm_tags') === '1' && seo_opt('noindex_tags') !== '1') {
        foreach ($pdo->query("SELECT t.id, t.slug, MAX(COALESCE(p.updated_at, p.date)) m FROM tags t JOIN post_tag pt ON pt.tag_id = t.id JOIN posts p ON p.id = pt.post_id AND p.status = 'published' WHERE t.is_active = 1" . edu_sm_exclude_terms('t.id') . " GROUP BY t.id ORDER BY t.name") as $t) $rows[] = [$b . '/tag/' . $t['slug'] . '-' . $t['id'], $t['m']];
    } elseif ($type === 'author' && seo_opt('sm_authors') === '1' && seo_opt('noindex_authors') !== '1') {
        foreach ($pdo->query("SELECT a.slug, MAX(COALESCE(p.updated_at, p.date)) m FROM authors a JOIN posts p ON p.author_id = a.id AND p.status = 'published' WHERE a.slug IS NOT NULL AND a.slug <> '' GROUP BY a.id ORDER BY a.name") as $a) $rows[] = [$b . '/author/' . $a['slug'], $a['m']];
    } elseif ($type === 'state' && seo_opt('sm_states') === '1') {
        foreach ($pdo->query("SELECT s.slug, MAX(COALESCE(p.updated_at, p.date)) m FROM states s JOIN posts p ON p.state_id = s.id AND p.status = 'published' GROUP BY s.id ORDER BY s.state_name") as $s) $rows[] = [$b . '/state-jobs/' . $s['slug'], $s['m']];
    } else {
        edu_sm_not_found();
        return;
    }
    edu_sm_urlset($rows);
}


/** "Exclude Posts" setting (post IDs) as SQL. */
function edu_sm_exclude_sql(string $alias = ''): string
{
    $ids = array_filter(array_map('intval', explode(',', (string)seo_opt('sm_exclude_posts'))));
    return $ids ? " AND {$alias}id NOT IN (" . implode(',', $ids) . ")" : '';
}

/** "Exclude Terms" setting (category / tag IDs) as SQL. */
function edu_sm_exclude_terms(string $col): string
{
    $ids = array_filter(array_map('intval', explode(',', (string)seo_opt('sm_exclude_terms'))));
    return $ids ? " AND $col NOT IN (" . implode(',', $ids) . ")" : '';
}

/** Google News sitemap in Rank Math's format: posts of the last 2 days, publication name and language from Sitemap Settings → News Sitemap. */
function edu_sm_news(PDO $pdo): void
{
    edu_sm_headers();
    $b = edu_sm_base();
    $ex = array_filter(array_map('intval', explode(',', (string)seo_opt('news_exclude_cats'))));
    $st = $pdo->query("SELECT p.id, p.slug, p.title, p.date, LEFT(p.content, 4000) AS c FROM posts p WHERE p.status = 'published' AND p.date >= NOW() - INTERVAL 2 DAY" . edu_sm_exclude_sql('p.') . ($ex ? " AND p.category_id NOT IN (" . implode(',', $ex) . ")" : '') . " ORDER BY p.date DESC LIMIT 1000");
    $name = trim((string)seo_opt('news_name')) ?: edu_site_name();
    $lang = preg_match('/^[a-z]{2,3}$/', (string)seo_opt('news_language')) ? seo_opt('news_language') : 'en';
    echo '<?xml version="1.0" encoding="UTF-8"?><?xml-stylesheet type="text/xsl" href="' . preg_replace('#^https?:#', '', $b) . '/news-sitemap.xsl"?>' . "\n";
    echo '<urlset xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd http://www.google.com/schemas/sitemap-news/0.9 http://www.google.com/schemas/sitemap-news/0.9/sitemap-news.xsd" xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:news="http://www.google.com/schemas/sitemap-news/0.9">' . "\n";
    foreach ($st as $p) {
        echo "\t<url>\n\t\t<loc>" . edu_sm_x($b . postUrl($p['slug'], (int)$p['id'])) . "</loc>\n\t\t<news:news>\n\t\t\t<news:publication>\n\t\t\t\t<news:name>" . edu_sm_x($name) . "</news:name>\n\t\t\t\t<news:language>" . (function_exists('edu_text_lang') ? edu_text_lang($p['title'] . ' ' . $p['c']) : $lang) . "</news:language>\n\t\t\t</news:publication>\n\t\t\t<news:publication_date>" . edu_sm_date($p['date']) . "</news:publication_date>\n\t\t\t<news:title><![CDATA[" . str_replace(']]>', ']]]]><![CDATA[>', $p['title']) . "]]></news:title>\n\t\t</news:news>\n\t</url>\n";
    }
    echo "</urlset>\n<!-- XML Sitemap generated by " . edu_sm_x(edu_site_name()) . " SEO -->";
}
